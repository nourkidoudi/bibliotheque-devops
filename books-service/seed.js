const seed = async () => {
  try {
    await db.sequelize.authenticate();
    await db.sequelize.sync({ alter: true });
    console.log('🔄 Connected to database for seeding...');

    // Seed categories
    for (const cat of categories) {
      const [category, created] = await db.Category.findOrCreate({
        where: { name: cat.name },
        defaults: cat,
      });
      if (created) console.log(`✨ Created category: ${category.name}`);
    }

    // Seed books
    for (const bookData of books) {
      const [book, created] = await db.Book.findOrCreate({
        where: { isbn: bookData.isbn },
        defaults: bookData,
      });
      if (created) console.log(`📖 Added book: ${book.title}`);
    }

    console.log('🎉 Books service seeding complete!');
    process.exit(0);
  } catch (error) {
    console.error('❌ Seeding failed:', error);
    process.exit(1);
  }
};

seed();
